function patchFile(path, spec) {
  const info = lstatSync(path);
  if (!info.isFile() || info.isSymbolicLink()) throw new Error(`Pi auth-path patch refuses non-regular runtime file: ${spec.rel}`);
  const current = readFileSync(path, "utf8");
  if (current.includes(spec.marker ?? PI_AUTH_PATH_PATCH_MARKER)) {
    if (spec.patchedSha256 && sha256(current) !== spec.patchedSha256) {
      throw new Error(`Pi compatibility patch refused altered patched bytes: ${spec.rel}`);
    }
    return;
  }
  if (sha256(current) !== spec.sha256) throw new Error(`Pi auth-path patch refused unexpected bytes: ${spec.rel}`);
  const patched = spec.transform(current);
  if (spec.patchedSha256 && sha256(patched) !== spec.patchedSha256) {
    throw new Error(`Pi compatibility patch produced unexpected bytes: ${spec.rel}`);
  }
  const temporary = `${path}.claude-harness-auth-path-${randomUUID()}.tmp`;
  writeFileSync(temporary, patched, { encoding: "utf8", mode: info.mode & 0o777 });
  renameSync(temporary, path);
}


