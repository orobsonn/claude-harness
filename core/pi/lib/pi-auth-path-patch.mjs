function sha256(content) {
  return createHash("sha256").update(content).digest("hex");
}

function replaceExactly(content, from, to, expected = 1) {
  const count = content.split(from).length - 1;
  if (count !== expected) throw new Error(`Pi auth-path patch expected ${expected} occurrence(s), found ${count}`);
  return content.split(from).join(to);
}

function mark(content) {
  return content.includes(PI_AUTH_PATH_PATCH_MARKER) ? content : `// ${PI_AUTH_PATH_PATCH_MARKER}\n${content}`;
}

